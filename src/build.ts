import { compareStrings } from "./load.js";
import type { Exercise, ExerciseSummary } from "./types.js";

const HEADER = "// Generated by `npm run generate` from exercises/*.json. Do not edit.\n\n";

const json = (value: unknown): string => JSON.stringify(value, null, 4);

const toSummary = ({ steps: _steps, ...summary }: Exercise): ExerciseSummary => summary;

export const renderCatalog = (exercises: readonly Exercise[]): string =>
    `${HEADER}import type { ExerciseSummary } from "../types.js";\n\n` +
    `export const exercises: readonly ExerciseSummary[] = ${json(exercises.map(toSummary))};\n`;

export const renderSteps = (exercises: readonly Exercise[]): string =>
    `${HEADER}export const steps: Readonly<Record<string, readonly string[]>> = ` +
    `${json(Object.fromEntries(exercises.map((exercise) => [exercise.id, exercise.steps])))};\n`;

// Apps keep ids in workout history, so the lock only ever grows. A removed id is reported, never dropped.
export const updateIdLock = (
    locked: readonly string[],
    current: readonly string[]
): { ids: string[]; removed: string[] } => {
    const currentIds = new Set(current);
    return {
        ids: [...new Set([...locked, ...current])].sort(compareStrings),
        removed: locked.filter((id) => !currentIds.has(id)),
    };
};
