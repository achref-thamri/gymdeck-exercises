import { describe, expect, test } from "vitest";

import { renderCatalog, renderSteps, updateIdLock } from "../src/build.js";
import { validExercise } from "./fixtures.js";

const bench = validExercise({ tips: ["Feet flat."] });
const squat = validExercise({ id: "squat", name: "Squat", steps: ["Stand tall.", "Sit down and stand up."] });

describe("renderCatalog", () => {
    test("is a typed module of every exercise without its steps", () => {
        const source = renderCatalog([bench, squat]);
        expect(source).toMatch(/^\/\/ Generated by `npm run generate`/);
        expect(source).toContain("export const exercises: readonly ExerciseSummary[] = ");
        expect(source).toContain('"tips": [\n');
        expect(source).not.toContain('"steps"');
        expect(source).not.toContain("Sit down and stand up.");
    });
});

describe("renderSteps", () => {
    test("maps each id to its steps", () => {
        const source = renderSteps([bench, squat]);
        expect(source).toContain("export const steps: Readonly<Record<string, readonly string[]>> = ");
        expect(source).toContain('"squat": [\n        "Stand tall.",\n        "Sit down and stand up."\n    ]');
    });
});

describe("updateIdLock", () => {
    test("adds new ids in sorted order", () => {
        expect(updateIdLock(["squat"], ["bench", "squat"])).toEqual({ ids: ["bench", "squat"], removed: [] });
    });

    test("reports locked ids that no longer exist", () => {
        expect(updateIdLock(["bench", "squat"], ["squat"])).toEqual({ ids: ["bench", "squat"], removed: ["bench"] });
    });
});
